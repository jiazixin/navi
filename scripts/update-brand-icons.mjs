// Refresh the three bundled brand paths without retaining a second application icon library.
// Run with Node from any working directory.
import { execFileSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const version = '16.27.1'
const repositoryRoot = resolve(import.meta.dirname, '..')
const temporary = mkdtempSync(join(tmpdir(), 'navi-brand-icons-'))
try {
  const output = execFileSync('npm', ['pack', `simple-icons@${version}`, '--ignore-scripts', '--json'], { cwd: temporary, encoding: 'utf8', timeout: 60_000 })
  const packages = JSON.parse(output)
  if (packages.length !== 1 || packages[0].filename !== `simple-icons-${version}.tgz`) throw new Error('Unexpected npm archive')
  execFileSync('tar', ['-xzf', packages[0].filename], { cwd: temporary, timeout: 30_000 })
  const metadata = JSON.parse(readFileSync(join(temporary, 'package/package.json'), 'utf8'))
  if (metadata.version !== version || metadata.license !== 'CC0-1.0') throw new Error('Unexpected icon metadata')
  const icons = await import(pathToFileURL(join(temporary, 'package/index.mjs')).href)
  const destination = resolve(repositoryRoot, 'web/src/features/search/brandIcons.ts')
  const header = '// Generated by node scripts/update-brand-icons.mjs; do not edit.\n// Source: simple-icons@16.27.1 (CC0-1.0), https://github.com/simple-icons/simple-icons\n'
  const definitions = ['siGithub', 'siClaude', 'siGooglegemini'].map((name) => {
    if (typeof icons[name]?.path !== 'string') throw new Error(`Missing icon ${name}`)
    return `export const ${name} = { path: ${JSON.stringify(icons[name].path)} }\n`
  })
  mkdirSync(resolve(repositoryRoot, 'web/src/features/search'), { recursive: true })
  writeFileSync(destination, header + definitions.join('\n'))
  execFileSync(resolve(repositoryRoot, 'web/node_modules/.bin/prettier'), ['--write', destination], { cwd: repositoryRoot, stdio: 'inherit', timeout: 30_000 })
} finally {
  rmSync(temporary, { recursive: true, force: true })
}
